"""Generate dsp/engine/fom_rings_tables.h: Rings' tables in integers, for the fixed-point port.

The float values come from Mutable's own dsp/ref/eurorack/rings/resources.cc (the reference), so the port and the
reference share their tables exactly; the rest is computed here, where there is floating point.

  tools/gen_rings_tables.py            (rewrites dsp/engine/fom_rings_tables.h)"""
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "dsp/ref/eurorack/rings/resources.cc"
OUT = ROOT / "dsp/engine/fom_rings_tables.h"
RATE = 44100


def lut(name):
    m = re.search(r"const float " + name + r"\[\] = \{(.*?)\};", SRC.read_text(), re.S)
    return [float(x) for x in re.findall(r"[-+]?[0-9.]+(?:e[-+]?[0-9]+)?", m.group(1))]


def rows(vals, per=8, fmt="{}"):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(fmt.format(v) for v in vals[i:i + per]) + ",")
    return "\n".join(out)


def main():
    decades = lut("lut_4_decades")
    stiffness = lut("lut_stiffness")
    assert len(decades) == 257 and len(stiffness) == 257
    q_q8 = [round(500.0 * v * 256) for v in decades]                     # Resonator's q = 500 * lut_4_decades, Q8
    stiff_q24 = [round(v * (1 << 24)) for v in stiffness]
    exp2_q30 = [round(2.0 ** (i / 256.0) * (1 << 30)) for i in range(257)]   # 2^(i/256), Q30
    note_q32 = [round(440.0 * 2.0 ** ((n - 69) / 12.0) / RATE * 2 ** 32) for n in range(128)]   # f / fs, Q32
    # stmlib's SoftLimit(x) = x (27 + x^2) / (27 + 9 x^2) as a gain over |x| in [0, 4], 64 points per unit, Q16
    soft_q16 = [round((27 + (i / 64) ** 2) / (27 + 9 * (i / 64) ** 2) * 65536) for i in range(257)]
    assert max(q_q8) < 2 ** 32 and max(note_q32) < 2 ** 32

    OUT.write_text(f"""/* SPDX-License-Identifier: MIT
 * Generated by tools/gen_rings_tables.py: do not edit. Rings' tables in integers for the fixed-point port. The float
 * values are Mutable Instruments' own (dsp/ref/eurorack/rings/resources.cc, MIT, Emilie Gillet). */
#ifndef FOM_RINGS_TABLES_H
#define FOM_RINGS_TABLES_H

#include <stdint.h>

namespace fom {{

/* 500 * lut_4_decades: the resonators' base Q over DAMPING, Q8 (257 points: index * 256) */
static const uint32_t kRingsQBaseQ8[257] = {{
{rows(q_q8, 6, "{}u")}
}};

/* lut_stiffness: the partials' stretch over STRUCTURE, Q24 (257 points) */
static const int32_t kRingsStiffnessQ24[257] = {{
{rows(stiff_q24, 6)}
}};

/* 2^(i / 256), Q30: the fraction of an octave (exp2 of a fixed-point number) */
static const uint32_t kExp2FracQ30[257] = {{
{rows(exp2_q30, 6, "{}u")}
}};

/* SoftLimit's gain (27 + x^2) / (27 + 9 x^2) for |x| = i / 64, 0..4, Q16 */
static const uint32_t kSoftLimitGainQ16[257] = {{
{rows(soft_q16, 8, "{}u")}
}};

/* MIDI note n -> frequency / {RATE} Hz, Q32 */
static const uint32_t kNoteFreqQ32[128] = {{
{rows(note_q32, 6, "{}u")}
}};

}}  // namespace fom

#endif
""")
    print(f"{OUT.relative_to(ROOT)}: q base {min(q_q8)}..{max(q_q8)}, stiffness {min(stiff_q24)}..{max(stiff_q24)}")


if __name__ == "__main__":
    main()
