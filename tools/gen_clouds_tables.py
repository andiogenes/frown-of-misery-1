"""Generate dsp/engine/fom_clouds_tables.h: Clouds' tables in integers for the fixed-point port, and the resamplers
between the FM-1's 44.1 kHz and Clouds' own 32 kHz.

The float values come from Mutable's own dsp/ref/eurorack/clouds/resources.cc (the reference), so the port and the
reference share their tables exactly; the rest is computed here, where there is floating point.

  tools/gen_clouds_tables.py            (rewrites dsp/engine/fom_clouds_tables.h; needs numpy)"""
import math
import re
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "dsp/ref/eurorack/clouds/resources.cc"
UNITS = ROOT / "dsp/ref/eurorack/stmlib/dsp/units.cc"
OUT = ROOT / "dsp/engine/fom_clouds_tables.h"
TAPS = 16                       # per phase, both resamplers
CUTOFF = 14500.0                # Hz, both: under 32 kHz's Nyquist with the transition of 16 taps
BETA = 5.0                      # Kaiser window (about 50 dB down)


def lut(name, src=SRC):
    m = re.search(r"const float " + name + r"\[\] = \{(.*?)\};", src.read_text(), re.S)
    return [float(x) for x in re.findall(r"[-+]?[0-9.]+(?:e[-+]?[0-9]+)?", m.group(1))]


def rows(vals, per=8, fmt="{}"):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(fmt.format(v) for v in vals[i:i + per]) + ",")
    return "\n".join(out)


def polyphase(up, fs_in):
    """A windowed sinc at fs_in * up, cut at CUTOFF, as up phases of TAPS taps: phase p, tap k is h[p + k up] (the
    tap for the input k samples back); each phase sums to 1 (Q15: 32768), so DC passes exactly."""
    n = TAPS * up
    t = (np.arange(n) - (n - 1) / 2.0) / up                    # in input samples
    h = np.sinc(2 * CUTOFF / fs_in * t) * np.kaiser(n, BETA)
    out = []
    for p in range(up):
        ph = h[p::up][:TAPS]
        q = np.round(ph / ph.sum() * 32768).astype(int)
        q[np.argmax(np.abs(q))] += 32768 - q.sum()             # exact unity at DC
        out.append([int(v) for v in q])
    return out


def float_parts(v):
    """a float32 as mantissa * 2^exponent, the mantissa in [2^23, 2^24)"""
    f = float(np.float32(v))
    m, e = math.frexp(f)                                       # f = m 2^e, m in [0.5, 1)
    mi = int(m * (1 << 24))
    assert mi * 2.0 ** (e - 24) == f and (1 << 23) <= mi < (1 << 24)
    return mi, e - 24


def cosine_approx_coefficient(freq):
    """stmlib's CosineOscillator::InitApproximate, in float32 as the module computes it: the iir coefficient"""
    f32 = np.float32
    frequency = f32(freq)
    sign = f32(16.0)
    frequency = f32(frequency - f32(0.25))
    if frequency < 0:
        frequency = -frequency
    else:
        if frequency > f32(0.5):
            frequency = f32(frequency - f32(0.5))
        else:
            sign = f32(-16.0)
    return f32(f32(sign * frequency) * f32(f32(1.0) - f32(f32(2.0) * frequency)))


def main():
    grain = lut("lut_grain_size")
    window = lut("lut_window")
    xin, xout = lut("lut_xfade_in"), lut("lut_xfade_out")
    assert len(grain) == 257 and len(window) == 4097 and len(xin) == 17 and len(xout) == 17
    assert all(v == int(v) for v in grain)
    window_q16 = [min(65535, round(v * 65536)) for v in window[:4096]] + [65535]   # (1.0: the one value over)
    xin_q30 = [round(v * (1 << 30)) for v in xin]
    xout_q30 = [max(0, round(v * (1 << 30))) for v in xout]
    high = [float_parts(v) for v in lut("lut_pitch_ratio_high", UNITS)]
    low = [float_parts(v) for v in lut("lut_pitch_ratio_low", UNITS)]
    assert len(high) == 256 and len(low) == 256
    down = polyphase(320, 44100.0)                             # 44.1 -> 32 kHz: up 320, down 441
    up = polyphase(441, 32000.0)                               # 32 -> 44.1 kHz: up 441, down 320
    # the reverb's two LFOs: SetLFOFrequency(f / 32000) inits the oscillator at f / 32000 * 32 (float32)
    f32 = np.float32
    lfo = []
    for hz in (0.5, 0.3):
        c = cosine_approx_coefficient(f32(f32(f32(hz) / f32(32000.0)) * f32(32.0)))
        lfo.append(int(round(float(c) * (1 << 29))))
        assert float(c) * (1 << 29) == lfo[-1]                # exact in Q29 (a float32 near 2)

    OUT.write_text(f"""/* SPDX-License-Identifier: MIT
 * Generated by tools/gen_clouds_tables.py: do not edit. Clouds' tables in integers for the fixed-point port. The float
 * values are Mutable Instruments' own (dsp/ref/eurorack/clouds/resources.cc, MIT, Emilie Gillet). */
#ifndef FOM_CLOUDS_TABLES_H
#define FOM_CLOUDS_TABLES_H

#include <stdint.h>

namespace fom {{

/* lut_grain_size: a grain's length in samples at 32 kHz over SIZE (257 points: index * 256), all integers */
static const int32_t kCloudsGrainSize[257] = {{
{rows([int(v) for v in grain], 8)}
}};

/* lut_window: the grains' smooth window over half a grain (4097 points), Q16 (the last, 1.0, as 65535) */
static const uint16_t kCloudsWindowQ16[4097] = {{
{rows(window_q16, 12, "{}u")}
}};

/* lut_xfade_in / lut_xfade_out: the dry/wet crossfade (17 points), Q30 */
static const int32_t kCloudsXfadeInQ30[17] = {{
{rows(xin_q30, 6)}
}};
static const int32_t kCloudsXfadeOutQ30[17] = {{
{rows(xout_q30, 6)}
}};

/* stmlib's lut_pitch_ratio_high and lut_pitch_ratio_low (SemitonesToRatio's), as their float32 values exactly:
 * mantissa (2^23..2^24) times 2^exponent */
static const int32_t kPitchRatioHighM[256] = {{
{rows([m for m, _ in high], 8)}
}};
static const int8_t kPitchRatioHighE[256] = {{
{rows([e for _, e in high], 16)}
}};
static const int32_t kPitchRatioLowM[256] = {{
{rows([m for m, _ in low], 8)}
}};
static const int8_t kPitchRatioLowE[256] = {{
{rows([e for _, e in low], 16)}
}};

/* the reverb's LFOs (0.5 and 0.3 Hz): CosineOscillator's approximate coefficient as the module's float32 has it, Q29 */
static const int32_t kCloudsReverbLfoQ29[2] = {{ {lfo[0]}, {lfo[1]} }};

/* the resamplers: polyphase windowed sincs ({TAPS} taps a phase, cut at {CUTOFF:.0f} Hz, Kaiser beta {BETA}), Q15, each
 * phase summing to 1; phase p, tap k weighs the input k samples back */
static const int32_t kCloudsSrcTaps = {TAPS};
/* 44.1 -> 32 kHz: output n is at input n * 441 / 320; its phase (n * 441) % 320 */
static const int16_t kCloudsSrcDown[320][{TAPS}] = {{
{chr(10).join("    {" + ", ".join(str(v) for v in ph) + "}," for ph in down)}
}};
/* 32 -> 44.1 kHz: output n is at input n * 320 / 441; its phase (n * 320) % 441 */
static const int16_t kCloudsSrcUp[441][{TAPS}] = {{
{chr(10).join("    {" + ", ".join(str(v) for v in ph) + "}," for ph in up)}
}};

}}  // namespace fom

#endif
""")
    print(f"{OUT.relative_to(ROOT)}: grain {min(grain):.0f}..{max(grain):.0f}, lfo {lfo}")


if __name__ == "__main__":
    main()
